import numpy as np

def henon_graph(D: int) -> np.ndarray:
    A = np.zeros((D, D), dtype=int)
    for i in range(D):
        A[i, i] = 1
        if i > 0:
            A[i, i - 1] = 1
    return A


def lorenz96_graph(D: int) -> np.ndarray:
    A = np.zeros((D, D), dtype=int)
    for i in range(D):
        A[i, i] = 1
        A[i, (i + 1) % D] = 1
        A[i, (i - 1) % D] = 1
        A[i, (i - 2) % D] = 1
    return A


